@pytest.mark.parametrize('mutation',['quote','hash','lines','future_cutoff','claim_company','dependency','causal_gap'])
def test_provenance_or_false_gap_closure_detected(fixture,mutation):
    gold,corpus,state=fixture
    if mutation=='quote':state['claims'][0]['text']='公司披露：“增长已独立证实”'
    if mutation=='hash':state['evidence'][0]['evidence_sha256']='b'*64
    if mutation=='lines':state['evidence'][0]['line_end']=999
    if mutation=='future_cutoff':state['context']['as_of_date']='2025-01-01'
    if mutation=='claim_company':state['claims'][0]['company_id']='688082.SH'
    if mutation=='dependency':state['claims'][0]['calculation_ids']=['unknown']
    if mutation=='causal_gap':state['supplement']={'gaps':[{'gap_type':'INDEPENDENT_CONFIRMATION','status':'RESOLVED','gap_id':'bad'}]}
    assert audit_state(state,gold,corpus)['issues']


def test_gold_order_or_duplicate_cannot_self_certify(fixture):
    gold,corpus,_=fixture
    gold['rows'][0]['values']={'2023':'130','2024':'100'}
    with pytest.raises(ValueError):anchor_gold(gold,corpus)
    gold['rows'].append(deepcopy(gold['rows'][0]))
    with pytest.raises(ValueError):gold_values(gold)


