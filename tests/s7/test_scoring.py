def test_literal_gold_anchors_and_independent_formulas(fixture):
    gold,corpus,state=fixture
    assert len(anchor_gold(gold,corpus))==3
    result=audit_state(state,gold,corpus)
    assert result['observations']['correct']==6
    assert result['calculations']['correct']==8
    assert not result['issues']
    assert result['semantic_review']['status']=='PENDING_INDEPENDENT_HUMAN_REVIEW'


@pytest.mark.parametrize('field,value',[('standard_value','999'),('fiscal_year',2022),('standard_unit','CNY_WANYUAN'),
    ('document_published_on','2024-01-01'),('document_sha256','b'*64),('statement_scope','PARENT'),('currency','USD'),
    ('period_start','2024-02-01'),('document_id','other')])
def test_bad_fact_metadata_not_accepted(fixture,field,value):
    gold,corpus,state=fixture
    state['observations'][0][field]=value
    result=audit_state(state,gold,corpus)
    assert result['observations']['correct']==5
    assert result['issues']
    assert result['observations']['expected']==6


def test_missing_fact_keeps_denominator(fixture):
    gold,corpus,state=fixture
    state['observations'].pop()
    r=audit_state(state,gold,corpus)
    assert r['observations']['correct']==5 and r['observations']['expected']==6 and r['observations']['missing']==1


@pytest.mark.parametrize('mutation',['wrong_value','wrong_unit','wrong_status','nan','extra_calculation'])
def test_calculation_mutation_detected(fixture,mutation):
    gold,corpus,state=fixture
    c=state['calculations']['002371.SZ']['revenue_growth']
    if mutation=='wrong_value':c['value']='30'
    if mutation=='wrong_unit':c['output_unit']='PERCENTAGE_POINT'
    if mutation=='wrong_status':c['status']='NEGATIVE_BASE'
    if mutation=='nan':c['value']='NaN'
    if mutation=='extra_calculation':state['calculations']['002371.SZ']['invented']={'value':'100'}
    r=audit_state(state,gold,corpus)
    assert r['calculations']['errors'] or r['issues']
    assert r['calculations']['expected']==8


def test_negative_base_is_not_a_growth_percentage(fixture):
    gold,_,_=fixture
    gold['rows'][1]['values']['2023']='-20'
    oracle=expected_calculations(gold_values(gold))['002371.SZ']
    assert oracle['operating_cash_flow_net_growth']['status']=='NEGATIVE_BASE'
    assert oracle['operating_cash_flow_net_growth']['value'] is None
    assert oracle['ocf_revenue_ratio_2023']['value']==Decimal('-0.2')
    assert oracle['revenue_ocf_growth_gap_pp']['status']=='INCOMPARABLE'


def test_zero_denominator(fixture):
    gold,_,_=fixture
    gold['rows'][0]['values']['2023']='0'
